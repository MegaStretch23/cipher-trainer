"""Offline helper (not needed to use the trainer): rebuild data.json / data.js from public-domain Project Gutenberg texts.
  python3 -I build_data.py DIR_WITH_pg*.txt   ->  writes data.json and data.js next to this file
Counts every English quadgram (letters only, A-Z), keeps the TOP quadgrams, stores each as an integer round(100*log10(count/total)); unseen quadgrams get FLOOR.
Integer scores keep the Python and JavaScript breakers bit-identical."""
import json, math, re, sys
from pathlib import Path

TOP = 9000
d = Path(sys.argv[1]); here = Path(__file__).resolve().parent
quad, uni, total, ntext = {}, [0] * 26, 0, 0
for f in sorted(d.glob("pg*.txt")):
    t = f.read_text(encoding="utf-8", errors="replace")
    a = t.find("*** START"); b = t.find("*** END")
    if a >= 0: t = t[t.index("\n", a):]
    if b >= 0: t = t[:t.find("*** END")]
    s = re.sub(r"[^A-Z]", "", t.upper()); ntext += len(s)
    for i in range(len(s) - 3): quad[s[i:i + 4]] = quad.get(s[i:i + 4], 0) + 1
    for ch in s: uni[ord(ch) - 65] += 1
    total += len(s) - 3
top = sorted(quad.items(), key=lambda kv: (-kv[1], kv[0]))[:TOP]
q = {k: round(100 * math.log10(c / total)) for k, c in top}
floor = round(100 * math.log10(0.5 / total))
ul = sum(uni); freq = [round(u / ul, 5) for u in uni]
cover = sum(c for _, c in top) / total
data = {"floor": floor, "freq": freq, "quad": q, "source": "Project Gutenberg #1342, 2701, 11, 1661, 84, 98 (public domain), %d letters; top %d quadgrams cover %.1f%% of all quadgrams" % (ntext, TOP, 100 * cover)}
(here / "data.json").write_text(json.dumps(data, separators=(",", ":"), sort_keys=True), encoding="utf-8")
(here / "data.js").write_text("/* generated by build_data.py - do not edit */\n(function (g) { g.CIPHER_DATA = " + json.dumps(data, separators=(",", ":"), sort_keys=True) + "; })(typeof window !== 'undefined' ? window : globalThis);\n", encoding="utf-8")
print(data["source"], "floor", floor, "size", (here / "data.json").stat().st_size)
